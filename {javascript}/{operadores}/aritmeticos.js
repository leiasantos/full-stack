// Valores de exemplo
let a = 10
let b = 3

// Adição
console.log("Adição: 10 + 3 = ", a + b)

// Subtração
console.log("Subtração: 10 - 3 = ", a - b)

// Multiplicação
console.log("Multiplicação: 10 * 3 = ", a * b)

// Divisão
console.log("Divisão: 10 / 3 = ", a / b)

// Resto da divisão (módulo)
console.log("Resto da divisão: 10 % 3 = ", a % b)

// Exponenciação (potência)
console.log("Exponenciação: 10 ** 3 = ", a ** b)
// Operador == (igual)
// Compara apenas o valor (faz coerção de tipo)
console.log("5 == '5' :", 5 == "5", "- compara apenas o valor, por isso retorna true")

// Operador === (igual estrito)
// Compara valor e tipo
console.log("5 === '5' :", 5 === "5", "- compara valor e tipo, por isso retorna false")

// Operador != (diferente)
// Verifica se os valores são diferentes (com coerção)
console.log("10 != 5 :", 10 != 5, "- verifica se os valores são diferentes")

// Operador !== (diferente estrito)
// Verifica valor e tipo
console.log("10 !== '10' :", 10 !== "10", "- verifica valor e tipo, por isso retorna true")

// Operador > (maior que)
console.log("8 > 3 :", 8 > 3, "- verifica se 8 é maior que 3")

// Operador < (menor que)
console.log("8 < 3 :", 8 < 3, "- verifica se 8 é menor que 3")

// Operador >= (maior ou igual)
console.log("10 >= 10 :", 10 >= 10, "- verifica se é maior ou igual")

// Operador <= (menor ou igual)
console.log("5 <= 2 :", 5 <= 2, "- verifica se é menor ou igual")



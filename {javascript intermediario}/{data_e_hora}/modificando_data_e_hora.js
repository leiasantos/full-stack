let date = new Date("April 7, 2026 14:10:00")

//Modificando o ano.
date.setFullYear(2030)

//Modificando o mês
date.setMonth(6)

//Modificando o dia
date.setDate(10)

//Modificando a hora
date.setHours(18)

//Modificando o minuto
date.setMinutes(15)

//Modificando o segundo
date.setSeconds(30)

console.log(date);

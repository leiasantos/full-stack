
let users = []
console.log(users);

//Adicionando um item no final do Array
users.push("Bella")
users.push("Rodrigo")
users.push("Clara")
users.push("Ricardo")
users.push("Julia")
console.log(users);

//Adicionando um item no inicio do Array
users.unshift("Carlos")
console.log(users);

//Removendo un item do inicio do Array
users.shift()
console.log(users);

//Removendo un item do final do Array
users.pop()
console.log(users);
